//! Concrete row types, kept in sync with the compiled registry.

use super::{
    BTreeMap, Cell, ColumnBinding, Cow, Decimal, RawTable, RowDecoder, RowMeta, RowPlan, RowRef,
    RowView, Sink,
};

macro_rules! typed_tables {
    ($( $variant:ident($row_type:ident) => $table_name:literal {
        $( $field:ident : $value_type:ty => $field_name:literal ),* $(,)?
    } ),* $(,)?) => {
        $(
            #[doc = concat!("Typed `", $table_name, "` row, including unmodeled source cells.")]
            #[derive(Debug, Clone, PartialEq, Eq)]
            pub struct $row_type<'a> {
                /// Raw source coordinates and unmodeled cells.
                pub meta: RowMeta<'a>,
                $(
                    #[doc = concat!("XER `", $table_name, ".", $field_name, "`.")]
                    pub $field: Cell<'a, $value_type>,
                )*
            }

            impl RowView for $row_type<'_> {
                fn meta(&self) -> &RowMeta<'_> { &self.meta }
                fn visit_fields(&self, visitor: &mut dyn FnMut(&'static str, Cow<'_, str>)) {
                    $( visitor($field_name, self.$field.encode()); )*
                }
            }

            impl<'a> $row_type<'a> {
                const FIELDS: &'static [&'static str] = &[$( $field_name ),*];

                fn decode(mut decoder: RowDecoder<'a, '_>) -> Self {
                    Self { meta: decoder.meta(), $( $field: decoder.cell($field_name), )* }
                }
            }
        )*

        /// A recognized table, preserving its source position and concrete row type.
        #[derive(Debug, Clone, PartialEq, Eq)]
        pub enum TypedTable<'a> {
            $(
                #[doc = concat!("Rows from XER `", $table_name, "`.")]
                $variant {
                    /// Index of the original raw table.
                    source_index: usize,
                    /// Typed rows in original order.
                    rows: Vec<$row_type<'a>>,
                },
            )*
        }

        impl TypedTable<'_> {
            /// Exact XER table name.
            #[must_use]
            pub const fn name(&self) -> &'static str {
                match self { $( Self::$variant { .. } => $table_name, )* }
            }

            /// Raw table index; repeated table names have different indices.
            #[must_use]
            pub const fn source_index(&self) -> usize {
                match self { $( Self::$variant { source_index, .. } => *source_index, )* }
            }

            /// Number of rows, including rows with malformed cells.
            #[must_use]
            pub fn len(&self) -> usize {
                match self { $( Self::$variant { rows, .. } => rows.len(), )* }
            }

            /// Whether the table contains no rows.
            #[must_use]
            pub fn is_empty(&self) -> bool { self.len() == 0 }

            /// Visit every row while retaining access to original source coordinates.
            pub fn visit_rows(&self, visitor: &mut dyn FnMut(&dyn RowView)) {
                match self { $( Self::$variant { rows, .. } => {
                    for row in rows { visitor(row); }
                }, )* }
            }
        }

        pub(super) fn decode_table<'a>(table: &'a RawTable, source_index: usize,
            columns: &BTreeMap<&'a str, ColumnBinding>, sink: &mut Sink) -> Option<TypedTable<'a>> {
            match table.name.as_str() {
                $( $table_name => {
                    let plan = RowPlan::new(table, columns, $row_type::FIELDS);
                    Some(TypedTable::$variant {
                        source_index,
                        rows: table.rows.iter().enumerate().map(|(index, row)| {
                            $row_type::decode(RowDecoder {
                                table, row, source: RowRef { table: source_index, row: index },
                                plan: &plan, next: 0, sink,
                            })
                        }).collect(),
                    })
                }, )*
                _ => None,
            }
        }
    };
}

